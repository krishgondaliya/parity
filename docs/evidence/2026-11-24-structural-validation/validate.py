"""Validate the structural method against the cut-out method, token for token, wherever both compute.

Run from the repo root: `uv run python docs/evidence/2026-11-24-structural-validation/validate.py`
Writes results.md next to this file. Two header policies:
- "special": the header token must be one the tokenizer declares special (the rule as decided);
- "added": any token in the tokenizer's added-token table (for comparison only).
"""

from __future__ import annotations

from dataclasses import astuple
from pathlib import Path

from parity.fixtures import load_all
from parity.references.template import (
    TemplateReferenceError,
    _generation_prompt_renders,
    _span_by_cut_out,
    _tokenize_with_offsets,
    declared_special_ids,
    model_chat_template,
    render_text,
    structural_span,
)
from parity.release import load_release
from parity.targets import CALIBRATION, PHASE0_TARGETS

OUT = Path(__file__).parent / "results.md"


def main() -> None:
    lines = [
        "# Structural method vs cut-out method",
        "",
        "Generated by `validate.py`. A turn is compared only where both methods compute; "
        "fields compared: token_start, token_end, token_message_end, token_message_start.",
        "",
        "| Model | Header policy | Turns | Cut-out computes | Structural computes | Both | Agree | Disagree | Structural only |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    details = []
    for target in (CALIBRATION,) + PHASE0_TARGETS:
        release = load_release(target)
        tok = release.tokenizer
        template = model_chat_template(tok)
        policies = {"special": declared_special_ids(tok), "added": frozenset(tok.added_tokens_decoder)}
        for policy, header_ids in policies.items():
            counts = dict(turns=0, cut=0, structural=0, both=0, agree=0, disagree=0, only=0)
            for fx in load_all():
                full = render_text(tok, fx.messages, fx.tools, template)
                ids, offsets = _tokenize_with_offsets(tok, full)
                try:
                    renders, seen = _generation_prompt_renders(tok, fx, template, full)
                except TemplateReferenceError:
                    continue
                for k in fx.assistant_indices:
                    counts["turns"] += 1
                    before, prompt = renders[k]
                    try:
                        cut = _span_by_cut_out(release, fx, template, k, full, ids, offsets, before, prompt, seen)
                    except TemplateReferenceError:
                        cut = None
                    found = structural_span(release, fx, template, k, full, ids, offsets, before, header_ids)
                    structural = None if isinstance(found, str) else found[0]
                    counts["cut"] += cut is not None
                    counts["structural"] += structural is not None
                    if cut is not None and structural is not None:
                        counts["both"] += 1
                        a, b = astuple(cut)[:5], astuple(structural)[:5]
                        if a == b:
                            counts["agree"] += 1
                        else:
                            counts["disagree"] += 1
                            details.append(f"- DISAGREE {target.repo_id} [{policy}] {fx.id} message {k}: cut-out {a} vs structural {b}")
                    elif structural is not None:
                        counts["only"] += 1
                        prefix = found[1]
                        span = structural
                        details.append(
                            f"- structural only: {target.repo_id} [{policy}] {fx.id} message {k}: header-to-content "
                            f"{prefix!r}; span {tok.decode(ids[span.token_start:span.token_end])!r}"
                        )
            c = counts
            lines.append(
                f"| {target.repo_id} | {policy} | {c['turns']} | {c['cut']} | {c['structural']} | {c['both']} | "
                f"{c['agree']} | {c['disagree']} | {c['only']} |"
            )
    lines += ["", "## Details", ""] + (details or ["(none)"]) + [""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
