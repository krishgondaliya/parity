"""Write docs/evidence/golden-review.md: the reference's zones, for a human to check by eye.

Run from the repo root: `uv run python docs/evidence/golden_review.py`

Every token of each render is shown in its zone: must-train inside [[ ]],
neutral inside { }, must-not-train as plain text. The text is the exact
render, so newlines are real newlines.
"""

from __future__ import annotations

from pathlib import Path

from parity.fixtures import FIXTURE_IDS, load_fixture
from parity.references.template import Zone, model_chat_template, render_reference
from parity.release import load_release
from parity.targets import CALIBRATION, PHASE0_TARGETS

OUT = Path(__file__).parent / "golden-review.md"
WRAP = {Zone.MUST_TRAIN: ("[[", "]]"), Zone.NEUTRAL: ("{", "}"), Zone.MUST_NOT_TRAIN: ("", "")}


def marked(release, ref) -> str:
    tokenizer = release.tokenizer
    pieces, run, zone = [], [], None
    for token, z in zip(ref.input_ids, ref.zones):
        if z != zone and run:
            pieces.append(_wrapped(tokenizer, run, zone))
            run = []
        run.append(token)
        zone = z
    if run:
        pieces.append(_wrapped(tokenizer, run, zone))
    return "".join(pieces)


def _wrapped(tokenizer, ids, zone) -> str:
    text = tokenizer.decode(ids, skip_special_tokens=False, clean_up_tokenization_spaces=False)
    left, right = WRAP[zone]
    return f"{left}{text}{right}"


def section(title: str, note: str, release, ref) -> list[str]:
    spans = ", ".join(
        f"message {s.message_index}" + (f" (pre-fill missing: {s.prefill_missing!r})" if s.prefill_missing else "")
        for s in ref.spans
    )
    return [f"## {title}", "", note, "", f"Assistant spans: {spans}.", "", "````text", marked(release, ref), "````", ""]


def main() -> None:
    qwen3 = load_release(CALIBRATION)
    deepseek = load_release(next(t for t in PHASE0_TARGETS if t.repo_id.startswith("deepseek-ai/")))
    lines = [
        "# Golden review: the reference's zones, by eye",
        "",
        "Generated by `docs/evidence/golden_review.py` from `parity.references.template.render_reference`.",
        "",
        "- `[[ ]]` must-train: the assistant's content through its stop token.",
        "- `{ }` neutral: the separator after the stop token (never fails either way).",
        "- Plain text: must-not-train (system, user and tool text, role headers, generation prompts).",
        "",
        "What to look for: every `[[ ]]` should be exactly what the model must learn to generate, and nothing "
        "the model is given should sit inside `[[ ]]`.",
        "",
        f"Calibration model: `{CALIBRATION.spec}`, its own template, default options.",
        "",
    ]
    for fid in FIXTURE_IDS:
        fixture = load_fixture(fid)
        lines += section(f"Qwen3: `{fid}`", fixture.title + ".", qwen3, render_reference(qwen3, fixture))

    lines += section(
        "DeepSeek V4.1: `single_turn` (the DeepSeek golden)",
        "The generation prompt `<｜Assistant｜><think>` is prompt side; the model writes `</think>`, the answer and "
        "EOS. No separator follows the EOS. The template injects a default system prompt. DeepSeek's history turns "
        "(fixtures with two or more assistant turns) still refuse; see docs/DECISIONS.md, 2026-11-24.",
        deepseek,
        render_reference(deepseek, load_fixture("single_turn")),
    )

    template = model_chat_template(qwen3.tokenizer)
    tail = template[template.index("{%- if add_generation_prompt %}") :]
    non_thinking = template.replace(
        tail, tail.replace("enable_thinking is defined and enable_thinking is false", "true")
    )
    lines += section(
        "Anchoring example: Qwen3 non-thinking, `multi_turn`",
        "Qwen3's own template with its non-thinking generation prompt, which pre-fills an empty think block. "
        "History turns render without it, so their content is anchored right after the role header; the last "
        "turn has the block, prompt side.",
        qwen3,
        render_reference(qwen3, load_fixture("multi_turn"), non_thinking, "test:qwen3-non-thinking"),
    )
    lines += [
        "## For your judgment",
        "",
        "- DeepSeek history turns render `<｜Assistant｜></think>`. If they are ever delimited, should `</think>` be "
        "must-train (where the renders stop agreeing) or prompt side (the template emits it with the header)?",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
