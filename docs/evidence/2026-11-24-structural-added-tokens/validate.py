"""Re-run the structural-vs-cut-out agreement check under the added-token header guard, on every model and mode.

Run from the repo root: `uv run python docs/evidence/2026-11-24-structural-added-tokens/validate.py`
Writes results.md next to this file.

The guard under test (docs/DECISIONS.md, 2026-11-24): the header and the stop token are each a single token the
tokenizer declares, special or added, and neither token's text appears in any message's content. A turn is compared
only where both methods compute (fields: token_start, token_end, token_message_end, token_message_start).
Decision rule (the human's): use the structural method for DeepSeek only if it agrees everywhere both compute AND
that agreement covers more than one model family. Otherwise DeepSeek keeps refusing.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import astuple
from pathlib import Path

from parity.fixtures import load_all
from parity.references.template import (
    TemplateReferenceError,
    _generation_prompt_renders,
    _span_by_cut_out,
    _tokenize_with_offsets,
    declared_special_ids,
    declared_token_ids,
    model_chat_template,
    render_text,
    structural_span,
)
from parity.release import load_release
from parity.serving import SERVING_MODES, ServingModeError, template_kwargs
from parity.targets import CALIBRATION, PHASE0_TARGETS

OUT = Path(__file__).parent / "results.md"


def reason_class(reason: str) -> str:
    return reason.split(": ", 1)[1] if ": " in reason else reason


def main() -> None:
    lines = [
        "# Structural method vs cut-out, added-token header guard",
        "",
        "Generated by `validate.py`. Header policy `declared` = special or added, with the content-absence guard "
        "(the new rule); `special` = the old rule, for comparison.",
        "",
        "| Model | Mode | Header policy | Turns | Cut-out computes | Structural computes | Both | Agree | Disagree | Structural only |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    details, reasons = [], Counter()
    agreeing_models: set[str] = set()
    disagreements = 0
    for target in (CALIBRATION,) + PHASE0_TARGETS:
        release = load_release(target)
        tok = release.tokenizer
        template = model_chat_template(tok)
        for mode in SERVING_MODES:
            try:
                kw = template_kwargs(release, mode)
            except ServingModeError:
                lines.append(f"| {target.repo_id} | {mode} | - | (no such mode) | | | | | | |")
                continue
            for policy, header_ids in (("declared", declared_token_ids(tok)), ("special", declared_special_ids(tok))):
                c = Counter()
                for fx in load_all():
                    full = render_text(tok, fx.messages, fx.tools, template, **kw)
                    ids, offsets = _tokenize_with_offsets(tok, full)
                    try:
                        renders, seen = _generation_prompt_renders(tok, fx, template, full, kw)
                    except TemplateReferenceError:
                        continue
                    for k in fx.assistant_indices:
                        c["turns"] += 1
                        before, prompt = renders[k]
                        try:
                            cut = _span_by_cut_out(release, fx, template, k, full, ids, offsets, before, prompt, seen, kw)
                        except TemplateReferenceError:
                            cut = None
                        found = structural_span(
                            release, fx, template, k, full, ids, offsets, before, header_ids, template_kwargs=kw
                        )
                        structural = None if isinstance(found, str) else found[0]
                        if structural is None and policy == "declared":
                            reasons[(target.repo_id, reason_class(found))] += 1
                        c["cut"] += cut is not None
                        c["structural"] += structural is not None
                        if cut is not None and structural is not None:
                            c["both"] += 1
                            a, b = astuple(cut)[:5], astuple(structural)[:5]
                            if a == b:
                                c["agree"] += 1
                                if policy == "declared":
                                    agreeing_models.add(target.repo_id)
                            else:
                                c["disagree"] += 1
                                disagreements += policy == "declared"
                                details.append(f"- DISAGREE {target.repo_id} [{mode}, {policy}] {fx.id} message {k}: cut-out {a} vs structural {b}")
                        elif structural is not None and policy == "declared":
                            c["only"] += 1
                            span = structural
                            details.append(
                                f"- structural only: {target.repo_id} [{mode}] {fx.id} message {k}: header-to-content "
                                f"{found[1]!r}; span {tok.decode(ids[span.token_start:span.token_end])!r}"
                            )
                lines.append(
                    f"| {target.repo_id} | {mode} | {policy} | {c['turns']} | {c['cut']} | {c['structural']} | {c['both']} | "
                    f"{c['agree']} | {c['disagree']} | {c['only']} |"
                )
    families = sorted(agreeing_models)
    use = disagreements == 0 and len(families) > 1
    lines += [
        "",
        "## Decision rule",
        "",
        f"- Disagreements under the new guard: {disagreements}.",
        f"- Model families where both methods compute and agree under the new guard: {len(families)} ({', '.join(families) or 'none'}).",
        f"- Use the structural method for DeepSeek: **{'yes' if use else 'no'}** "
        "(needs zero disagreements and more than one model family).",
        "",
        "## Why the structural method refuses (new guard), turns per reason",
        "",
        "| Model | Reason | Turns |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {m} | {r} | {n} |" for (m, r), n in sorted(reasons.items())]
    lines += ["", "## Details", ""] + (details or ["(none)"]) + [""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
